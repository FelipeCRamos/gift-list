import 'package:equatable/equatable.dart';

import 'enums.dart';

/// A gift list owned by a creator. `pixKey`/`merchantName` are per-list (the
/// profile only prefills them). The `private ⇒ loginRequired` invariant is
/// enforced by a DB CHECK constraint and by `ListEditorCubit` client-side.
class GiftList extends Equatable {
  const GiftList({
    required this.id,
    required this.ownerId,
    required this.slug,
    required this.title,
    required this.occasion,
    required this.pixKey,
    required this.pixKeyType,
    required this.merchantName,
    required this.visibility,
    required this.contributorAuth,
    required this.isPublished,
    required this.createdAt,
    this.description,
    this.coverImageUrl,
    this.eventDate,
  });

  final String id;
  final String ownerId;
  final String slug;
  final String title;
  final Occasion occasion;
  final String pixKey;
  final PixKeyType pixKeyType;

  /// Name shown in the BR Code (field 59) — ASCII, <=25 chars.
  final String merchantName;
  final ListVisibility visibility;
  final ContributorAuth contributorAuth;
  final bool isPublished;
  final DateTime createdAt;
  final String? description;
  final String? coverImageUrl;
  final DateTime? eventDate;

  GiftList copyWith({
    String? title,
    Occasion? occasion,
    String? pixKey,
    PixKeyType? pixKeyType,
    String? merchantName,
    ListVisibility? visibility,
    ContributorAuth? contributorAuth,
    bool? isPublished,
    String? description,
    String? coverImageUrl,
    DateTime? eventDate,
  }) {
    return GiftList(
      id: id,
      ownerId: ownerId,
      slug: slug,
      title: title ?? this.title,
      occasion: occasion ?? this.occasion,
      pixKey: pixKey ?? this.pixKey,
      pixKeyType: pixKeyType ?? this.pixKeyType,
      merchantName: merchantName ?? this.merchantName,
      visibility: visibility ?? this.visibility,
      contributorAuth: contributorAuth ?? this.contributorAuth,
      isPublished: isPublished ?? this.isPublished,
      createdAt: createdAt,
      description: description ?? this.description,
      coverImageUrl: coverImageUrl ?? this.coverImageUrl,
      eventDate: eventDate ?? this.eventDate,
    );
  }

  @override
  List<Object?> get props => [
    id,
    ownerId,
    slug,
    title,
    occasion,
    pixKey,
    pixKeyType,
    merchantName,
    visibility,
    contributorAuth,
    isPublished,
    createdAt,
    description,
    coverImageUrl,
    eventDate,
  ];
}

